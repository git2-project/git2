-- auth-svc: fixed roles, users.role, teams and team members in the auth_svc schema
-- Design: docs/design/identity-v0.md. The list of roles ships with git2;
-- what each role may do lives in Go code in auth-svc, not in these tables.

-- The fixed role list, read by the console to fill its dropdowns. A new or
-- changed role is a new migration, never a hand edit.
-- (name, scope) is unique so assignments can reference it with a composite
-- foreign key and an instance role can never be stored as a team role.
CREATE TABLE IF NOT EXISTS auth_svc.roles (
    name        TEXT NOT NULL,
    scope       TEXT NOT NULL,
    description TEXT NOT NULL,
    CONSTRAINT roles_pkey            PRIMARY KEY (name),
    CONSTRAINT roles_name_scope_key  UNIQUE (name, scope),
    CONSTRAINT roles_scope_check     CHECK (scope IN ('instance', 'team'))
);

INSERT INTO auth_svc.roles (name, scope, description) VALUES
    ('admin',      'instance', 'Everything in the admin plane'),
    ('auditor',    'instance', 'Read-only admin plane: users, teams, settings, audit log'),
    ('user',       'instance', 'The Dash plane; the default for new accounts'),
    ('maintainer', 'team',     'Rename the team, add and remove members'),
    ('member',     'team',     'Belongs to the team; repository access comes through it')
ON CONFLICT (name) DO NOTHING;

-- Every user has exactly one instance role. role_scope is a constant the
-- application never writes; it only exists for the composite foreign key.
-- Existing rows become 'user'.
-- tokens_valid_after is set when a user is disabled: sessions that began
-- before it are refused at refresh, also after the user is enabled again.
-- NULL means the user was never disabled.
ALTER TABLE auth_svc.users
    ADD COLUMN IF NOT EXISTS role               TEXT NOT NULL DEFAULT 'user',
    ADD COLUMN IF NOT EXISTS role_scope         TEXT NOT NULL DEFAULT 'instance',
    ADD COLUMN IF NOT EXISTS tokens_valid_after TIMESTAMPTZ;

-- Dropped first so the file can be run again, like the rest of it.
ALTER TABLE auth_svc.users
    DROP CONSTRAINT IF EXISTS users_role_scope_instance,
    DROP CONSTRAINT IF EXISTS users_role_fkey,
    ADD CONSTRAINT users_role_scope_instance CHECK (role_scope = 'instance'),
    ADD CONSTRAINT users_role_fkey FOREIGN KEY (role, role_scope)
        REFERENCES auth_svc.roles (name, scope);

-- Setup and the last-admin rule ask "which active admins exist?".
DROP INDEX IF EXISTS auth_svc.users_admin_idx;
CREATE INDEX IF NOT EXISTS users_active_admin_idx
    ON auth_svc.users (id) WHERE role = 'admin' AND is_active;

-- id is a UUIDv7 generated by the service, like users.id. name is a
-- lowercase slug with the same rule as the contract's Slug, since it will
-- appear in URLs.
CREATE TABLE IF NOT EXISTS auth_svc.teams (
    id          UUID         PRIMARY KEY,
    name        VARCHAR(39)  NOT NULL,
    description VARCHAR(500) NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT teams_name_key  UNIQUE (name),
    CONSTRAINT teams_name_slug CHECK (name ~ '^[a-z0-9][a-z0-9_-]{2,38}$')
);

-- One row per (team, user) with the member's team role. Deleting a team
-- deletes its memberships; users are disabled, never deleted, so a user
-- with memberships cannot be removed by accident.
CREATE TABLE IF NOT EXISTS auth_svc.team_members (
    team_id    UUID        NOT NULL,
    user_id    UUID        NOT NULL,
    role       TEXT        NOT NULL DEFAULT 'member',
    role_scope TEXT        NOT NULL DEFAULT 'team',
    added_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT team_members_pkey PRIMARY KEY (team_id, user_id),
    CONSTRAINT team_members_team_fkey FOREIGN KEY (team_id)
        REFERENCES auth_svc.teams (id) ON DELETE CASCADE,
    CONSTRAINT team_members_user_fkey FOREIGN KEY (user_id)
        REFERENCES auth_svc.users (id) ON DELETE RESTRICT,
    CONSTRAINT team_members_role_scope_team CHECK (role_scope = 'team'),
    CONSTRAINT team_members_role_fkey FOREIGN KEY (role, role_scope)
        REFERENCES auth_svc.roles (name, scope)
);

-- "Which teams is this user in?" — asked on every access check.
CREATE INDEX IF NOT EXISTS team_members_user_id_idx
    ON auth_svc.team_members (user_id);
